"""### Part 2: Advanced Preprocessing with Feature Scaling & Regularized Models

In this section, we will optimize our preprocessing pipeline by adding `StandardScaler` to the numerical features. This ensures that features with larger numeric ranges do not dominate the regression coefficients. We will also train a **Ridge Regression** model to introduce L2 regularization and compare its performance with our basic Linear Regression model.
"""

from sklearn.preprocessing import StandardScaler
from sklearn.linear_model import Ridge

# 1. Update the numerical transformer to include Feature Scaling (Standardization)
numeric_transformer_scaled = Pipeline(steps=[
    ("imputer", SimpleImputer(strategy="median")),
    ("scaler", StandardScaler())
])

# 2. Re-create preprocessor
preprocessor_scaled = ColumnTransformer(transformers=[
    ("num", numeric_transformer_scaled, numeric_features),
    ("cat", categorical_transformer, categorical_features)
])

# 3. Define the new Pipeline with Ridge Regression
ridge_model = Pipeline(steps=[
    ("preprocessor", preprocessor_scaled),
    ("regressor", Ridge(alpha=1.0))
])

# 4. Train the regularized model
ridge_model.fit(X_train, y_train)
print("Ridge Regression model with standardized features trained successfully!")

# Evaluate the Ridge model
y_pred_ridge = ridge_model.predict(X_test)

mae_r = mean_absolute_error(y_test, y_pred_ridge)
mse_r = mean_squared_error(y_test, y_pred_ridge)
rmse_r = np.sqrt(mse_r)
r2_r = r2_score(y_test, y_pred_ridge)

# Compare with previous Linear Regression
comparison_updated = pd.DataFrame({
    "Model": ["Mean Baseline", "Linear Regression (No Scaling)", "Ridge Regression (With Scaling)"],
    "MAE": [baseline_mae, mae, mae_r],
    "RMSE": [baseline_rmse, rmse, rmse_r],
    "R2": [baseline_r2, r2, r2_r]
})

display(comparison_updated)

